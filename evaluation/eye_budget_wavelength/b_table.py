# -*- coding: utf-8 -*-
"""Assemble the eleven-channel table from b_results.json (read-only on the result, writes b_table.md)."""
import io
import json
import os

HERE = r"<WORK_ROOT>\overnight_261015\B_input_channels"                # original branch-B folder: b_results.json, progress.md, run_stdout.txt (read only)
OUTD = r"<WORK_ROOT>\overnight_261015\fix_261015\B_input_channels"        # this fix folder
R = json.load(open(os.path.join(HERE, "b_results.json"), encoding="utf-8"))
K7 = ("eta_x", "eta_y", "leak_x", "leak_y", "refl_x", "refl_y", "refl_worst_sop")
S = R["stages"]
GRID = R["meta"]["grid_nm_C2"]
rows = {}
for rec in S.get("repro", []):
    k = int(rec["ch"])
    rows[k] = dict(src="stored (rounded lam %.2f nm)" % rec["lam_nm"], lam=rec["lam_nm"], v=rec["stored"],
                   v_new=rec, t=rec["t_s"])
for rec in S.get("new", []):
    k = int(rec["ch"])
    rows[k] = dict(src="NEW", lam=rec["lam_nm"], v={q: rec[q] for q in K7}, t=rec["t_s"])
bon = {int(r["ch"]): r for r in S.get("bonus", [])}
out = []
out.append("# Branch B table (generated by b_table.py from b_results.json), FIX ROUND 261015: wording and notes only, every number unchanged\n")
out.append("**Grid.** The eleven wavelengths are the 100 GHz grid ANCHORED AT 1550.000 nm (f0 = c / 1550.000 nm = %.4f THz, f0 + k x 100 GHz, k = -5..+5), not the ITU-T G.694.1 grid: every channel is offset by +14.49 GHz from the nearest 193.1 THz + n x 100 GHz frequency (for example 193.4 THz is 1550.116 nm and 193.9 THz is 1546.119 nm, against 1550.000 and 1546.003 nm here). Call them 'channels of the 100 GHz grid centred on 1550.000 nm', not 'ITU channels'.\n" % R["meta"]["f0_THz"] if "f0_THz" in R["meta"] else
           "**Grid.** The eleven wavelengths are the 100 GHz grid ANCHORED AT 1550.000 nm (f0 = c / 1550.000 nm = 193.4145 THz, f0 + k x 100 GHz, k = -5..+5), not the ITU-T G.694.1 grid: every channel is offset by +14.49 GHz from the nearest 193.1 THz + n x 100 GHz frequency (for example 193.4 THz is 1550.116 nm and 193.9 THz is 1546.119 nm, against 1550.000 and 1546.003 nm here). Call them 'channels of the 100 GHz grid centred on 1550.000 nm', not 'ITU channels'.\n")
out.append("## 1. Eleven channels, nG 901 (889 realised), Li liy / ff 1, hard design of sim752 (md5 L1 %s, L2 %s)\n"
           % (R["meta"]["density_md5_L1"][:8], R["meta"]["density_md5_L2"][:8]))
out.append("S = stored value of input2d.json at the rounded wavelength of _band(); NEW = computed here at the exact grid wavelength.\n")
out.append("| ch | grid nm (C2) | lam used nm | src | eta_x | eta_y | leak_x | leak_y | refl_x | refl_y | refl_worst_sop |")
out.append("|---|---|---|---|---|---|---|---|---|---|---|")
for k in range(5, -6, -1):
    r = rows.get(k)
    if r is None:
        out.append("| %+d | %.4f | -- | MISSING | | | | | | | |" % (k, GRID[str(k)]))
        continue
    v = r["v"]
    out.append("| %+d | %.4f | %.4f | %s | %.6f | %.6f | %.3e | %.3e | %.3e | %.3e | %.3e |"
               % (k, GRID[str(k)], r["lam"], "S" if r["src"].startswith("stored") else "NEW",
                  v["eta_x"], v["eta_y"], v["leak_x"], v["leak_y"], v["refl_x"], v["refl_y"], v["refl_worst_sop"]))
out.append("")
out.append("## 2. Reproduction of the five stored channels (new solve vs stored), tolerance 1e-6\n")
out.append("| ch | lam nm | max abs resid over 7 keys | worst key | verdict | needle (lam + 0.1 nm) max resid | needle verdict |")
out.append("|---|---|---|---|---|---|---|")
nd = {int(r["ch"]): r for r in S.get("needle", [])}
for rec in S.get("repro", []):
    k = int(rec["ch"])
    wk = max(rec["resid_abs"], key=rec["resid_abs"].get)
    n = nd.get(k)
    out.append("| %+d | %.2f | %.3e | %s | %s | %s | %s |"
               % (k, rec["lam_nm"], rec["max_resid"], wk, "PASS" if rec["passed"] else "FAIL",
                  ("%.3e" % n["max_resid"]) if n else "--",
                  ("caught (FAIL, as required)" if n["check_failed"] else "NOT CAUGHT") if n else "--"))
out.append("")
out.append("Per-key residual (abs), reproduction:\n")
out.append("| ch | " + " | ".join(K7) + " |")
out.append("|---|" + "---|" * len(K7))
for rec in S.get("repro", []):
    out.append("| %+d | " % int(rec["ch"]) + " | ".join("%.2e" % rec["resid_abs"][q] for q in K7) + " |")
out.append("")
if bon:
    out.append("## 3. Same-basis view: the four off-grid stored channels re-solved at their exact grid wavelength (channel 0 is already exact)\n")
    out.append("| ch | stored lam nm | exact nm | d eta_x (exact - stored) | d eta_y | d leak_x | d leak_y | d refl_worst |")
    out.append("|---|---|---|---|---|---|---|---|")
    for k in sorted(bon, reverse=True):
        b = bon[k]
        s = rows[k]["v"]
        out.append("| %+d | %.2f | %.4f | %+.2e | %+.2e | %+.2e | %+.2e | %+.2e |"
                   % (k, rows[k]["lam"], b["lam_nm"], b["eta_x"] - s["eta_x"], b["eta_y"] - s["eta_y"],
                      b["leak_x"] - s["leak_x"], b["leak_y"] - s["leak_y"],
                      b["refl_worst_sop"] - s["refl_worst_sop"]))
    out.append("")
# band summary on the exact-grid basis (stored five replaced by bonus, ch 0 by stored)
ex = {}
for k, r in rows.items():
    ex[k] = {q: r["v"][q] for q in K7}
for k, b in bon.items():
    ex[k] = {q: b[q] for q in K7}
if len(ex) == 11:
    out.append("## 4. Band summary, exact-grid basis (11 channels)\n")
    for q in ("eta_x", "eta_y"):
        vals = {k: ex[k][q] for k in ex}
        lo = min(vals, key=vals.get)
        hi = max(vals, key=vals.get)
        out.append("- %s: min %.6f at ch %+d, max %.6f at ch %+d, spread %.6f" % (q, vals[lo], lo, vals[hi], hi, vals[hi] - vals[lo]))
    for q in ("leak_x", "leak_y", "refl_x", "refl_y", "refl_worst_sop"):
        vals = {k: ex[k][q] for k in ex}
        hi = max(vals, key=vals.get)
        out.append("- %s: max %.3e at ch %+d" % (q, vals[hi], hi))
    out.append("")
    out.append("| ch | eta_x | eta_y | leak_x | leak_y | refl_x | refl_y | refl_worst_sop |")
    out.append("|---|---|---|---|---|---|---|---|")
    for k in range(5, -6, -1):
        v = ex[k]
        out.append("| %+d | %.6f | %.6f | %.3e | %.3e | %.3e | %.3e | %.3e |"
                   % (k, v["eta_x"], v["eta_y"], v["leak_x"], v["leak_y"], v["refl_x"], v["refl_y"], v["refl_worst_sop"]))
    out.append("")
allrec = [r for st in ("repro", "needle", "new", "bonus") for r in S.get(st, [])]
out.append("## 5. Runtime and memory\n")
out.append("- solves: %d, total solve time %.0f s, per solve %.0f-%.0f s (3 threads, cores 10-12)"
           % (len(allrec), sum(r["t_s"] for r in allrec), min(r["t_s"] for r in allrec), max(r["t_s"] for r in allrec)))
out.append("- process RSS max %.2f GB, peak working set at the last solve %.2f GB; affinity at end %s"
           % (R.get("rss_max_gb", float("nan")), allrec[-1]["peak_wset_gb"], R.get("affinity_end")))
out.append("- energy conservation max |sum - 1| over all solves: %.2e (Ex), %.2e (Ey); halves-vs-RT max %.2e"
           % (max(abs(r["energy_Ex"] - 1) for r in allrec), max(abs(r["energy_Ey"] - 1) for r in allrec),
              max(r["halves_vs_RT"] for r in allrec)))
out.append("- nG realised: %s" % sorted(set(r["nG_realised"] for r in allrec)))
# ---- 6. code versions and RAM-guard waits (added in the 261015 fix round)
M = R["meta"]
prog = io.open(os.path.join(HERE, "progress.md"), encoding="utf-8").read()
stdo = io.open(os.path.join(HERE, "run_stdout.txt"), encoding="utf-8").read()
waits_prog = [ln for ln in prog.splitlines() if "RAM wait" in ln]
waits_std = [ln for ln in stdo.splitlines() if "RAM wait" in ln]
guard_std = [ln for ln in stdo.splitlines() if "RAM GUARD" in ln]
assert len(waits_prog) == len(waits_std) == len(guard_std), (len(waits_prog), len(waits_std), len(guard_std))
out.append("")
out.append("## 6. Code versions and RAM-guard waits (added 261015, fix round)\n")
out.append("| File | md5 of the snapshot used here (B_input_channels\\snapshot\\) | md5 of the stored run (input2d.json, sim752) | equal |")
out.append("|---|---|---|---|")
for lab, a, b in (("Main_rcwa_input2d.py (driver)", "driver_md5_snapshot", "driver_md5_stored_run"), ("grcwa rcwa.py", "grcwa_rcwa_md5_snapshot", "grcwa_rcwa_md5_stored_run"),
                  ("scd_c_grating.py", "scd_c_grating_md5_snapshot", "scd_c_grating_md5_stored_run"), ("grcwa fft_funs.py", "grcwa_fft_funs_md5_snapshot", "grcwa_fft_funs_md5_stored_run"),
                  ("grcwa li_fmm.py", "grcwa_li_fmm_md5_snapshot", "grcwa_li_fmm_md5_stored_run")):
    out.append("| %s | %s | %s | %s |" % (lab, M[a][:8], M[b][:8], "yes" if M[a] == M[b] else "NO"))
out.append("")
out.append("Three files differ from the stored run, not two (the pre-fix report listed only the driver and rcwa.py): the driver, grcwa rcwa.py and scd_c_grating.py. Diffs checked in the fix round against the dated backups of the stored versions (all three are opt-in additions that leave the default path unchanged):")
out.append("- Main_rcwa_input2d.py 06ace7f9 -> 9f1ab1e8 (backup code_backup\\261013_asi_k_optin\\Main_rcwa_input2d.py.bak_124509): a helper _eps_keep() that returns float(real) for a lossless material (the old value, bit-identical default path) and the complex eps only for an 'a-Si_k*' name; one condition extended to accept 'a-Si_k*' names. This job uses material1 = 'a-Si'.")
out.append("- scd_c_grating.py 7db71c25 -> 09d205af (backup code_backup\\261013_asi_k_optin\\scd_c_grating.py.bak_124509): 8 added lines, six new material-table entries 'a-Si_k0' .. 'a-Si_k1e-1' (opt-in extinction sensitivity); nothing else.")
out.append("- grcwa rcwa.py 06aba348 -> b8dd79bb (backup code_backup\\261011_li_skew\\rcwa.py.bak_203442): the li_skew support (obj.li_raster = None by default; a rectangular-lattice guard that only raises on a skewed lattice with a non-default rule). The input metagrating lattice is rectangular.")
out.append("- Equivalence for THIS job is demonstrated numerically, not by the md5: the reproduction of the five stored channels (section 2) agrees to at most %.2e over all 7 keys, and every +0.1 nm needle was caught." % max(r["max_resid"] for r in S.get("repro", [])))
out.append("")
out.append("RAM-guard waits: **%d**, not three (progress.md and run_stdout.txt agree: %s). Each was a single skip by the in-driver RAM guard (about 2.6 GB needed, RAM use would have reached 72 %% > 70 %%) that cleared at the first retry (retry 0); no solve was dropped or repeated, and the numbers are unaffected." % (
    len(waits_prog), "; ".join(ln.split("RAM wait ")[0].strip("- []") + " " + ln.split("RAM wait ")[1].split(":")[0] for ln in waits_prog)))
out.append("")
open(os.path.join(OUTD, "b_table.md"), "w", encoding="utf-8").write("\n".join(out) + "\n")
print("\n".join(out))
